"""Generate `tables.rs`, the constant tables of the besselj port, from scipy 1.18.1's xsf sources.

    python rust/numeric/besselj/tables.py XSF_INCLUDE > rust/numeric/besselj/tables.rs

XSF_INCLUDE is the `include/xsf` directory of xsf as scipy 1.18.1 vendors it
(`subprojects/xsf/include/xsf` in the scipy-1.18.1 sdist). Every decimal literal is copied as
written: C++ and Rust both round it to the nearest double. A C initializer shorter than its
declared array is zero-filled, as C does.
"""
import re
import sys

AMOS = ['zunhj_ar', 'zunhj_br', 'zunhj_c', 'zunhj_alfa', 'zunhj_beta', 'zunhj_gama', 'dgamln_gln',
        'dgamln_cf']
CEPHES = {
    'jv.h': ['jv_PF2', 'jv_PF3', 'jv_PF4', 'jv_PG1', 'jv_PG2', 'jv_PG3', 'jv_lambda', 'jv_mu', 'jv_P1', 'jv_P2',
             'jv_P3', 'jv_P4', 'jv_P5', 'jv_P6', 'jv_P7'],
    'j0.h': ['j0_PP', 'j0_PQ', 'j0_QP', 'j0_QQ', 'j0_RP', 'j0_RQ'],
    'j1.h': ['j1_RP', 'j1_RQ', 'j1_PP', 'j1_PQ', 'j1_QP', 'j1_QQ'],
    'gamma.h': ['gamma_P', 'gamma_Q', 'gamma_STIR', 'gamma_A', 'gamma_B', 'gamma_C'],
    'rgamma.h': ['rgamma_R'],
    'airy.h': ['airy_AN', 'airy_AD', 'airy_APN', 'airy_APD', 'airy_BN16', 'airy_BD16', 'airy_BPPN', 'airy_BPPD',
               'airy_AFN', 'airy_AFD', 'airy_AGN', 'airy_AGD', 'airy_APFN', 'airy_APFD', 'airy_APGN', 'airy_APGD'],
}
LIT = re.compile(r'-?\d+(\.\d*)?([eE][+-]?\d+)?')


def table(text: str, name: str, per_row: int) -> str:
    m = re.search(r'constexpr double ' + name + r'\[(\d*)\] = \{(.*?)\};', text, re.S)
    if m is None:
        raise SystemExit(f'{name}: not found')
    body = re.sub(r'/\*.*?\*/', '', m.group(2), flags=re.S)
    body = re.sub(r'//[^\n]*', '', body)
    vals = [v.strip() for v in body.split(',') if v.strip()]
    if m.group(1):
        size = int(m.group(1))
        if len(vals) > size:
            raise SystemExit(f'{name}: {len(vals)} initializers for {size} elements')
        vals += ['0.0'] * (size - len(vals))
    for v in vals:
        if not LIT.fullmatch(v):
            raise SystemExit(f'{name}: unexpected literal {v!r}')
    lits = [v if ('.' in v or 'e' in v.lower()) else v + '.0' for v in vals]
    rows = [', '.join(lits[i:i + per_row]) for i in range(0, len(lits), per_row)]
    return (f'pub(super) const {name.upper()}: [f64; {len(lits)}] = [\n    ' + ',\n    '.join(rows)
            + ',\n];')


def main() -> None:
    base = sys.argv[1].rstrip('/') + '/'
    out = ['// GENERATED by rust/numeric/besselj/tables.py from scipy 1.18.1\'s xsf sources; do not',
           '// edit. The AMOS tables (xsf/amos/amos.h, Copyright (C) 2024 SciPy developers) and the',
           '// Cephes tables (xsf/cephes/*.h, Copyright Stephen L. Moshier; C++ translation by the',
           '// SciPy developers), BSD-3-Clause: notices in LICENSES_bundled.txt.']
    tables = []
    amos = open(base + 'amos/amos.h').read()
    tables += [table(amos, name, 4) for name in AMOS]
    for fname, names in CEPHES.items():
        text = open(base + 'cephes/' + fname).read()
        tables += [table(text, name, 3) for name in names]
    sys.stdout.write('\n'.join(out) + '\n\n' + '\n\n'.join(tables) + '\n')


if __name__ == '__main__':
    main()
