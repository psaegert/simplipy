"""Generate `harmonic_tables.rs`, the constant tables of the harmonic kernel (`harmonic.rs`).

Run from the repository root:

    python rust/numeric/harmonic_tables.py > rust/numeric/harmonic_tables.rs

Everything is computed with mpmath at 60 significant digits and rounded once to float64
(double-double constants keep the rounding residue as their low part):

* the centre polynomials: for each centre k = 1..K, the Chebyshev interpolant (mpmath
  ``chebyfit``) of D_k(t) = (H(k + t) - H(k)) / t on t in [-1/2, 1/2], of the lowest degree whose
  error |t (P_k(t) - D_k(t))| stays below 2^-64 times the smallest |H| the centre serves;
* the harmonic numbers H(k), Euler's gamma, ln 2, pi and the reciprocals 1/6, 1/12, 1/24;
* the asymptotic coefficients B_2j / (2j) of psi, up to the first term below 2^-64 H at
  x = K + 1/2;
* for ln: the reciprocals r_i of the knots 1 + i/128 on [1, 2), -ln r_i, and the Taylor tail
  of ln(1 + d);
* the Taylor tails of sin and cos (for pi cot(pi r)).
"""
import sys

import mpmath as mp

mp.mp.dps = 60
K = 8
REL = mp.mpf(2) ** -64


def _dd(v: mp.mpf) -> tuple[float, float]:
    hi = float(v)
    return hi, float(v - mp.mpf(hi))


#: Values clippy requires to be spelled by their std name (`approx_constant`).
_NAMED = {float(mp.pi): 'std::f64::consts::PI', float(mp.log(2)): 'std::f64::consts::LN_2'}


def _lit(x: float) -> str:
    x = float(x)
    if x in _NAMED:
        return _NAMED[x]
    s = repr(x)
    return s if ('.' in s or 'e' in s or 'inf' in s or 'nan' in s) else s + '.0'


def _dd_lit(v: mp.mpf) -> str:
    hi, lo = _dd(v)
    return f'Dd::new({_lit(hi)}, {_lit(lo)})'


def _d(k: int, t: mp.mpf) -> mp.mpf:
    if t == 0:
        return mp.psi(1, k + 1)
    return (mp.harmonic(k + t) - mp.harmonic(k)) / t


def _fit(k: int) -> tuple[list[mp.mpf], int]:
    grid = [mp.mpf(i) / 400 - mp.mpf(1) / 2 for i in range(401)]
    # centre 1 also serves H(t) = t (1/(1+t) + D_1(t)) on [-1/2, 1/2], whose bracket exceeds 1.2
    hmin = mp.mpf('0.6') if k == 1 else abs(mp.harmonic(k - mp.mpf(1) / 2))
    for n in range(6, 45):
        coeffs = list(mp.chebyfit(lambda t: _d(k, t), [-0.5, 0.5], n + 1))[::-1]
        worst = mp.mpf(0)
        for t in grid:
            acc = mp.mpf(0)
            for c in reversed(coeffs):
                acc = acc * t + c
            worst = max(worst, abs(t * (acc - _d(k, t))))
        if worst <= REL * hmin:
            return coeffs, n
    raise RuntimeError(f'centre {k}: no degree below 45 reaches the bound')


def main() -> None:
    out: list[str] = []
    w = out.append
    w('// GENERATED by rust/numeric/harmonic_tables.py (mpmath %s, 60 digits); do not edit.' % mp.__version__)
    w('// Regenerate: python rust/numeric/harmonic_tables.py > rust/numeric/harmonic_tables.rs')
    w('')
    w('use super::dd::Dd;')
    w('')
    w(f'/// The centres k = 1..=K of the polynomial range [1/2, K + 1/2).\npub(super) const K: usize = {K};')
    w('')
    c0, c1, tails = [], [], []
    for k in range(1, K + 1):
        coeffs, n = _fit(k)
        c0.append(_dd_lit(coeffs[0]))
        c1.append(_dd_lit(coeffs[1]))
        tails.append([float(c) for c in coeffs[2:]])
        print(f'centre {k}: degree {n}', file=sys.stderr)
    plen = max(len(t) for t in tails)
    w('/// D_k(t) = (H(k + t) - H(k)) / t ~ c0 + t (c1 + t P(t)): the two leading coefficients.')
    w('pub(super) const CENTRE_C0: [Dd; K] = [\n    ' + ',\n    '.join(c0) + ',\n];')
    w('pub(super) const CENTRE_C1: [Dd; K] = [\n    ' + ',\n    '.join(c1) + ',\n];')
    w('/// P_k: the remaining coefficients, constant term first, zero-padded to one length.')
    w(f'pub(super) const CENTRE_P: [[f64; {plen}]; K] = [\n    '
      + ',\n    '.join('[' + ', '.join(_lit(c) for c in t + [0.0] * (plen - len(t))) + ']' for t in tails)
      + ',\n];')
    w('/// H(k), k = 0..=K.')
    w('pub(super) const H_K: [Dd; K + 1] = [\n    ' + ',\n    '.join(_dd_lit(mp.harmonic(k)) for k in range(K + 1)) + ',\n];')
    x0 = mp.mpf(K) + mp.mpf(1) / 2
    na = next(n for n in range(2, 40)
              if abs(mp.bernoulli(2 * (n + 1)) / (2 * (n + 1)) / x0 ** (2 * (n + 1))) < REL * mp.harmonic(x0))
    asym = [_lit(float(mp.bernoulli(2 * j) / (2 * j))) for j in range(2, na + 1)]
    w('/// B_2j / (2j), j = 2..: the asymptotic series of psi past its 1/(12 x^2) term.')
    w(f'pub(super) const ASYM: [f64; {len(asym)}] = [' + ', '.join(asym) + '];')
    w(f'pub(super) const GAMMA: Dd = {_dd_lit(mp.euler)};')
    w(f'pub(super) const LN2: Dd = {_dd_lit(mp.log(2))};')
    w(f'pub(super) const PI: Dd = {_dd_lit(mp.pi)};')
    w(f'pub(super) const INV6: Dd = {_dd_lit(mp.mpf(1) / 6)};')
    w(f'pub(super) const INV12: Dd = {_dd_lit(mp.mpf(1) / 12)};')
    w(f'pub(super) const INV24: Dd = {_dd_lit(mp.mpf(1) / 24)};')
    # ln on [1, 2): f = c_i (1 + d) with c_i = 1 + i/LN_N, r_i = fl(1/c_i), |d| <= 2^-8;
    # ln f = -ln r_i + ln(1 + d), ln(1 + d) = d + d^2 (-1/2 + d/3 - d^2/4 + ...)
    ln_n = 128
    recips, logs = [], []
    for i in range(ln_n + 1):
        r = float(1 / (1 + mp.mpf(i) / ln_n))
        recips.append(_lit(r))
        logs.append(_dd_lit(-mp.log(mp.mpf(r))))
    ln_tail = [_lit(float(mp.mpf((-1) ** (j + 1)) / j)) for j in range(2, 9)]
    sin_tail = [_lit(float((-1) ** j / mp.factorial(2 * j + 1))) for j in range(2, 10)]
    cos_tail = [_lit(float((-1) ** j / mp.factorial(2 * j))) for j in range(3, 11)]
    w(f'/// ln on [1, 2) is read at LN_N + 1 knots c_i = 1 + i/LN_N.\npub(super) const LN_N: usize = {ln_n};')
    w('/// r_i: the f64 nearest 1/c_i.')
    w('pub(super) const LN_RECIP: [f64; LN_N + 1] = [' + ', '.join(recips) + '];')
    w('/// -ln r_i, exactly for the f64 r_i.')
    w('pub(super) const LN_LOG: [Dd; LN_N + 1] = [\n    ' + ',\n    '.join(logs) + ',\n];')
    w('/// (-1)^(j+1) / j, j = 2..: ln(1 + d) = d + d^2 (-1/2 + d/3 - ...).')
    w(f'pub(super) const LN_TAIL: [f64; {len(ln_tail)}] = [' + ', '.join(ln_tail) + '];')
    w('/// (-1)^j / (2j + 1)!, j = 2..: sin p past p - p^3/6.')
    w(f'pub(super) const SIN_TAIL: [f64; {len(sin_tail)}] = [' + ', '.join(sin_tail) + '];')
    w('/// (-1)^j / (2j)!, j = 3..: cos p past 1 - p^2/2 + p^4/24.')
    w(f'pub(super) const COS_TAIL: [f64; {len(cos_tail)}] = [' + ', '.join(cos_tail) + '];')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
